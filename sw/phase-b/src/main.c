/* ---- Phase-3 gamma / tone LUT: on-device fixed-point curve compute (parity) ----
 * Daemon sends gamma*10 only; firmware computes the 256-entry curve (no libm, no bulk
 * transport over UART). out[i]=round(255*(i/255)^(1/g)); verified <=1 LSB vs float pow. */
#ifdef GAMMA_GPIO_BASE
static unsigned g_gamma_tog = 0, g_gamma_swap = 0, g_gamma_byp = 1;

/* Commit one entry to the INACTIVE bank (flip the load toggle). gamma_lut is double-
 * buffered, so this never touches the displayed bank — load at any speed, no chroma. */
static void gamma_put(unsigned ch, unsigned addr, unsigned data)
{
    /* DATA-then-STROBE clock-domain crossing. Present ch/addr/data with the load toggle
     * UNCHANGED, let the data's 2-FF sync settle, THEN flip the toggle in a separate write.
     * The receiver detects the toggle edge (3-FF) only AFTER the data is already stable at
     * its q2 regs → no metastability skew between the toggle edge and the multi-bit data.
     * Writing data + toggle in one word raced (toggle edge could land a cycle off from the
     * settled data) → random per-entry corruption → gray turned chromatic (the persistent
     * #114 bug; double-buffer + usleep couldn't fix a fundamentally racy load). */
    u32 base = (g_gamma_byp ? 1u : 0u) | ((ch & 3u) << 2)
             | ((addr & 0xFFu) << 4) | ((data & 0xFFu) << 12) | (g_gamma_swap << 20);
    Xil_Out32(GAMMA_GPIO_BASE, base | (g_gamma_tog << 1));   /* 1) data; toggle unchanged */
    usleep(1);                                               /*    let the data CDC settle */
    g_gamma_tog ^= 1u;
    Xil_Out32(GAMMA_GPIO_BASE, base | (g_gamma_tog << 1));   /* 2) flip toggle → commit settled data */
    usleep(1);
}
/* Set bypass and optionally request a bank swap. Does NOT flip the load toggle, so no
 * spurious LUT write; the swap (if requested) commits atomically at the next SOF. */
static void gamma_set_byp_swap(unsigned bypass, unsigned do_swap)
{
    g_gamma_byp = bypass ? 1u : 0u;
    if (do_swap) g_gamma_swap ^= 1u;
    u32 w = (g_gamma_byp ? 1u : 0u) | (g_gamma_tog << 1) | (g_gamma_swap << 20);
    Xil_Out32(GAMMA_GPIO_BASE, w);
    usleep(1);
}

/* Q16 fixed-point pow (65536=1.0): integer power + iterated-sqrt fractional. */
static u32 isqrt64(u64 n)
{
    u64 x = 0, b = 1ull << 62;
    while (b > n) b >>= 2;
    while (b) { if (n >= x + b) { n -= x + b; x = (x >> 1) + b; } else x >>= 1; b >>= 2; }
    return (u32)x;
}
static u32 powq16(u32 x, u32 p)
{
    if (x == 0) return 0;
    u32 ip = p >> 16, fp = p & 0xFFFFu; int k;
    u64 result = 65536, base = x; u32 e = ip;
    while (e) { if (e & 1u) result = (result * base) >> 16; base = (base * base) >> 16; e >>= 1; }
    u32 root = x;
    for (k = 1; k <= 16; k++) { root = isqrt64(((u64)root) << 16); if (fp & (1u << (16 - k))) result = (result * root) >> 16; }
    return (u32)result;
}
/* gx10 = gamma*10 (22 = 2.2). 0 or 10 = off/linear (bypass). Computes + loads all 3 ch. */
static void gamma_load(unsigned gx10)
{
    if (gx10 == 0u || gx10 == 10u) {
        gamma_set_byp_swap(1, 0);           /* off / linear → bypass (no swap needed) */
        g_gamma = 0u;
        xil_printf("GAMMA: off (linear)\r\n");
        return;
    }
    /* Compute the curve into the INACTIVE bank (display untouched — no chroma at any load
     * speed), then enable + swap: the new bank goes live atomically at the next SOF. */
    u32 inv_q16 = 655360u / gx10;           /* (1/g) in Q16 */
    unsigned i;
    for (i = 0; i < 256; i++) {
        u32 x = (i == 255u) ? 65536u : ((u32)i * 65536u) / 255u;
        u32 v = powq16(x, inv_q16);
        u32 d = (v * 255u + 32768u) >> 16; if (d > 255u) d = 255u;
        gamma_put(0, i, (u8)d);
        gamma_put(1, i, (u8)d);
        gamma_put(2, i, (u8)d);
    }
    gamma_set_byp_swap(0, 1);               /* enable + swap-at-next-SOF */
    g_gamma = gx10;
    xil_printf("GAMMA: %u.%u\r\n", gx10 / 10u, gx10 % 10u);
}
#endif

#ifdef GEO_A_BASE
static unsigned g_re_w = FRAME_W, g_re_h = FRAME_H;
static int      g_re_x = 0, g_re_y = 0;     /* SIGNED shift in output px: +right/down, -left/up */
static unsigned g_re_anchor = 0;            /* scale anchor: 0 = image center (default), 1 = top-left corner */
static unsigned g_re_filt_mode = 0;         /* #107: 0=NN 1=2-tap box 2=H-bilinear 3=H+V-bilinear */
static unsigned g_re_hflip = 0, g_re_vflip = 0;  /* horizontal / vertical flip (180 = both) */
static unsigned g_re_matte = 0, g_re_engine = 0, g_re_blend = 0;
static void re_write_geometry(void)
{
    unsigned w = g_re_w, h = g_re_h;
    /* scale 1..300% of the output raster (w>OUT_RASTER => upscaled = zoom in).
     * 3x: out_w_win up to 3840 (<4095, 12-bit OK); centered base_x = (1280-3840)/2 = -1280 (within ±2047). */
    if (w < 1) w = 1; if (w > 3u*OUT_RASTER_W) w = 3u*OUT_RASTER_W;
    if (h < 1) h = 1; if (h > 3u*OUT_RASTER_H) h = 3u*OUT_RASTER_H;

    /* SIGNED window translation. Place the (scaled w x h) image at output
     *   (px,py) = anchor_base + user_shift.
     * anchor_base centers the image when the checkbox is OFF (center): for a zoomed
     * image this is negative. user_shift slides it — including clean off the edge, so
     * pixels leave the frame and matte fills the OPPOSITE edge. */
    int sx = g_re_x, sy = g_re_y;
    int base_x = g_re_anchor ? 0 : ((int)OUT_RASTER_W - (int)w) / 2;
    int base_y = g_re_anchor ? 0 : ((int)OUT_RASTER_H - (int)h) / 2;
    int px = base_x + sx;
    int py = base_y + sy;
    if (px >  2047) px =  2047; if (px < -2048) px = -2048;   /* 12-bit signed GPIO range */
    if (py >  2047) py =  2047; if (py < -2048) py = -2048;

    /* DDA seed = source col/row shown at the first ON-SCREEN output pixel. The
     * off-screen-left/top amount (output px) maps to source via IN/win. This one
     * formula produces BOTH the center-anchor crop (px<0 when zoomed) AND the
     * shift-induced crop (px<0 when shifted left). px>=0 => seed 0. */
    unsigned offx = (px < 0) ? (unsigned)(-px) : 0u;
    unsigned offy = (py < 0) ? (unsigned)(-py) : 0u;
    unsigned sc0 = (offx * FRAME_W) / w;
    unsigned sr0 = (offy * FRAME_H) / h;

    /* FLIP: backward DDA from the far-end seed. The seed is the source col/row the MIRROR
     * shows at the first ON-SCREEN pixel = floor((w-1-offx)*FRAME_W/w), where offx is the
     * off-screen-left amount (window-relative col of the first on-screen pixel). This makes
     * the mirrored content translate the SAME direction as un-flipped under shift — flip
     * mirrors the picture, the window still moves normally. Composes with zoom + shift. */
    if (g_re_hflip) { unsigned fj = (offx < w) ? (w - 1u - offx) : 0u; sc0 = (fj * FRAME_W) / w; }
    if (g_re_vflip) { unsigned fj = (offy < h) ? (h - 1u - offy) : 0u; sr0 = (fj * FRAME_H) / h; }
    if (sc0 > 0xFFFu) sc0 = 0xFFFu;
    if (sr0 > 0xFFFu) sr0 = 0xFFFu;

    unsigned hsi = FRAME_W / w, hsf = FRAME_W % w;   /* floor(IN_W/out_w), IN_W%out_w */
    unsigned vsi = FRAME_H / h, vsf = FRAME_H % h;
    /* #107a bilinear reciprocals: Q0.16 1/window, rounded; clamp 16-bit. */
    unsigned inv_w = (w > 0u) ? ((65536u + w/2u) / w) : 0xFFFFu; if (inv_w > 0xFFFFu) inv_w = 0xFFFFu;
    unsigned inv_h = (h > 0u) ? ((65536u + h/2u) / h) : 0xFFFFu; if (inv_h > 0xFFFFu) inv_h = 0xFFFFu;
    Xil_Out32(GEO_A_BASE + 0x00, ((h & 0xFFF) << 16) | (w & 0xFFF));
    Xil_Out32(GEO_A_BASE + 0x08, (((unsigned)py & 0xFFFu) << 16) | ((unsigned)px & 0xFFFu)); /* signed 12b */
    Xil_Out32(GEO_B_BASE + 0x00, ((hsf & 0xFFF) << 16) | (hsi & 0xFFF));
    Xil_Out32(GEO_B_BASE + 0x08, ((vsf & 0xFFF) << 16) | (vsi & 0xFFF));
    Xil_Out32(GEO_C_BASE + 0x00, g_re_matte & 0xFFFFFF);
    /* ch2: bit0=sel, [2:1]=blend, [14:3]=src_col0, [26:15]=src_row0, 28=hflip, 29=vflip, [31:30]=filt_mode (#107) */
    Xil_Out32(GEO_C_BASE + 0x08,
              ((g_re_filt_mode & 3u) << 30) |
              ((g_re_vflip ? 1u : 0u) << 29) | ((g_re_hflip ? 1u : 0u) << 28) |
              ((sr0 & 0xFFFu) << 15) | ((sc0 & 0xFFFu) << 3) |
              ((g_re_blend & 3u) << 1) | (g_re_engine ? 1u : 0u));
#if defined(INVW_GPIO_BASE) && !defined(WARP_BUILD)
    Xil_Out32(INVW_GPIO_BASE, (inv_h << 16) | (inv_w & 0xFFFFu));   /* #107a: bilinear weight reciprocals */
    /* NOTE: in the WARP build axi_gpio_12 is the MUX SEL, not INVW — never write it here or the mux
     * flips to passthrough (1080p master into 720p raster = black). Guarded by !WARP_BUILD. */
#endif
    xil_printf("GEO: %ux%u shift(%d,%d) %s flip(%u,%u) -> pos(%d,%d) seed(%u,%u) hstep=%u+%u/%u vstep=%u+%u/%u engine=%u blend=%u filt=%u invw=%u\r\n",
               w, h, sx, sy, g_re_anchor ? "TL" : "center", g_re_hflip, g_re_vflip, px, py, sc0, sr0,
               hsi, hsf, w, vsi, vsf, h, g_re_engine, g_re_blend, g_re_filt_mode, inv_w);
}
#endif

static void uart_dispatch(const char *line)
{
    if (line[0] == '\0') return;
    char op = line[0];
    const char *p = line + 1;
    unsigned a, b, c;
    if (op == 'J') {
        while (*p == ' ' || *p == '\t') p++;
        cp_dispatch_jsonrpc(p);
        return;
    }
    if (op == '?' || op == 'h') {
        cmd_help();
    } else if (op == 'i') {
        g_sat_q15 = 0x8000; g_sat_pct = 100;
        g_black_r = g_black_g = g_black_b = 0;
        g_white_r = g_white_g = g_white_b = 255;
        g_matrix_sat_pct = 100; g_matrix_preset = 0;
        /* also clear operator overrides (parity Phase 1) */
        g_mono = 0; g_bypass = 0; g_fade_level = 255; g_fade_to = 255; g_fade_step = 0; g_colortemp = 0;
        color_apply_state();
        color_matrix_identity();
    } else if (op == 's' && parse_uint(&p, &a)) {
        g_sat_pct = (a > 200) ? 200 : a;
        g_sat_q15 = color_sat_from_percent(a);
        color_apply_state();
    } else if (op == 'm' && parse_uint(&p, &a)) {
        g_matrix_sat_pct = (a > 200) ? 200 : a; g_matrix_preset = 2;
        color_matrix_saturation(color_sat_from_percent(a));
    } else if (op == 'g') {
        g_matrix_sat_pct = 0; g_matrix_preset = 1;
        color_matrix_saturation(0);
    } else if (op == 'b' && parse_uint(&p, &a) && parse_uint(&p, &b) && parse_uint(&p, &c)) {
        g_black_r = (u8)a; g_black_g = (u8)b; g_black_b = (u8)c;
        color_apply_state();
    } else if (op == 'w' && parse_uint(&p, &a) && parse_uint(&p, &b) && parse_uint(&p, &c)) {
        g_white_r = (u8)a; g_white_g = (u8)b; g_white_b = (u8)c;
        color_apply_state();
    } else if (op == 'r') {
        color_apply_state();   /* re-write triggers readback prints */
        color_matrix_identity(); /* same — re-emits MATRIX line */
    } else if (op == 'k') {
        /* iter14 (2026-05-31): runtime scaler kernel-mode toggle.
         *   k h <0|1|2|3>  — set H scaler kernel mode
         *   k v <0|1|2|3>  — set V scaler kernel mode
         *   k             — print current mode
         * Modes: 0=NN, 1=2-tap boxcar (production), 2=4-tap boxcar, 3=rsv.
         * GPIO 7 holds 4-bit value: [1:0]=H, [3:2]=V. */
#ifdef SCALER_KERNEL_GPIO_BASEADDR
        u32 cur = Xil_In32(SCALER_KERNEL_GPIO_BASEADDR);
        if (*p == ' ') p++;
        char axis = *p++;
        if (axis == '\0') {
            /* query */
            xil_printf("KERNEL: H=%u V=%u  (raw=0x%01x)\r\n",
                       (unsigned)(cur & 0x3), (unsigned)((cur >> 2) & 0x3),
                       (unsigned)(cur & 0xf));
        } else if ((axis == 'h' || axis == 'v') && parse_uint(&p, &a) && a <= 3) {
            if (axis == 'h') cur = (cur & ~0x3) | (a & 0x3);
            else             cur = (cur & ~0xC) | ((a & 0x3) << 2);
            Xil_Out32(SCALER_KERNEL_GPIO_BASEADDR, cur);
            xil_printf("KERNEL: H=%u V=%u  (k%c=%u)\r\n",
                       (unsigned)(cur & 0x3), (unsigned)((cur >> 2) & 0x3),
                       axis, a);
        } else {
            xil_printf("UART: usage 'k h|v <0-3>' or just 'k' to query\r\n");
        }
#else
        xil_printf("UART: kernel-mode GPIO not present in this build\r\n");
#endif
    } else if (op == 'W') {
        /* WARP live rotation: W <deg> [invx_q12] [invy_q12]  (invx/y default 4096=1.0x).
         *   W 30            — rotate 30 deg, 1:1 (centered crop of the master).
         *   W 0 6144 6144   — no rotation, 1.5x downscale (whole master into the raster).
         *   W               — query current. The prefetch LEAD auto-tracks the geometry
         *   (warp_calc_lead); use 'L <n>' to override live if an angle thrashes/underruns. */
#ifdef WARP_BUILD
        /* W <deg> [invx] [invy] [panx] [pany] [hf] [vf] [anchor] — daemon sends 8; firmware uses
         * deg/inv/pan/anchor (hf/vf parsed-and-ignored for now: flip not yet wired into the warp affine).
         * pan = OUTPUT px. anchor: 0 = scale about center (default), 1 = top-left corner. */
        int deg, px = 0, py = 0; unsigned ivx = 4096, ivy = 4096, t, hf = 0, vf = 0, anc = 0;
        if (parse_int(&p, &deg)) {
            if (parse_uint(&p, &t) && t >= 256u) ivx = t;
            if (parse_uint(&p, &t) && t >= 256u) ivy = t;
            parse_int(&p, &px); parse_int(&p, &py);   /* optional pan (output px, signed); default 0 */
            parse_uint(&p, &hf); parse_uint(&p, &vf); /* hf/vf: parsed, not yet applied */
            if (parse_uint(&p, &anc)) g_warp_anchor = anc ? 1u : 0u;  /* optional anchor (0=center,1=TL) */
            (void)hf; (void)vf;
            warp_set_rotation(deg, (int)ivx, (int)ivy, px, py);
        } else {
            xil_printf("WARP rot=%d invx=%d invy=%d lead=%u\r\n",
                       g_warp_deg, g_warp_invx, g_warp_invy, (unsigned)g_warp_lead);
        }
#else
        xil_printf("UART: 'W' is warp-only; no warp engine in this build\r\n");
#endif
    } else if (op == 'Z') {
        /* DECIMATE-ON-WRITE scale: Z <pct>  (10..200). <100 = scaler decimates
         * to a sub-window (clean downscale, no warp starve); >=100 = warp zoom.
         * 'Z' alone = query. */
#ifdef WARP_BUILD
        unsigned pct;
        if (parse_uint(&p, &pct)) {
            apply_scale(pct);
        } else {
            xil_printf("SCALE %u%% (Z <10-200> to set)\r\n", g_scale_pct);
        }
#else
        xil_printf("UART: 'Z' is warp-only; no warp engine in this build\r\n");
#endif
    } else if (op == 'R') {
        /* RUNTIME OUTPUT-RES SWITCH: R 720 | R 1080  (live, monitor re-syncs).
         * Only valid in a MAX=1920x1080 build (OUTPUT_1080P). 'R' alone = query. */
#if defined(WARP_BUILD) && defined(OUTPUT_1080P)
        unsigned res;
        if (parse_uint(&p, &res)) {
            set_output_mode(res >= 1080u ? 1080u : 720u);
        } else {
            xil_printf("OUTPUT %ux%u (R 720|1080 to switch)\r\n", g_out_w, g_out_h);
        }
#else
        xil_printf("UART: 'R' needs a MAX=1920x1080 (OUTPUT_1080P) warp build\r\n");
#endif
    } else if (op == 'L') {
        /* WARP prefetch LEAD override: L <n> sets a manual lead (0 = auto per-geometry); L = query.
         * Too DEEP a lead for a gentle rotation HARD-FREEZES (evicts unconsumed tiles); too shallow
         * underruns. Sweep this live to dial a new geometry in without a rebuild. */
#if defined(WARP_BUILD) && defined(LEAD_GPIO_BASE)
        unsigned n;
        if (parse_uint(&p, &n)) {
            g_warp_lead_ovr = n & 0x000FFFFFu;            /* 20-bit; 0 = auto */
            warp_set_rotation(g_warp_deg, g_warp_invx, g_warp_invy, g_warp_panx, g_warp_pany);  /* re-apply -> writes lead GPIO */
            xil_printf("WARP lead %s -> %u\r\n", g_warp_lead_ovr ? "OVERRIDE" : "AUTO", (unsigned)g_warp_lead);
        } else {
            xil_printf("WARP lead=%u (%s)\r\n", (unsigned)g_warp_lead, g_warp_lead_ovr ? "override" : "auto");
        }
#else
        xil_printf("UART: 'L' is warp-only; no warp engine in this build\r\n");
#endif
    } else if (op == 'M') {
        /* LOD mip fill (PHASE 1, STATIC source): snapshot the current frame into the L1/L2 mip rings, then
         * arm LOD so downscale below fit fetches the pre-shrunk copy (clean 51-100% / 50%). Source must be
         * static (SMPTE bars) — this is a one-shot CPU box-average, not a live generator. 'M 0' disarms. */
#if defined(WARP_BUILD) && defined(LEAD_GPIO_BASE)
        unsigned a;
        if (parse_uint(&p, &a) && a == 0u) {
            g_mip_valid = 0;
            warp_set_rotation(g_warp_deg, g_warp_invx, g_warp_invy, g_warp_panx, g_warp_pany); /* re-apply -> L0 */
            xil_printf("MIP: disarmed (LOD forced to L0)\r\n");
        } else {
            mip_fill_static();
            warp_set_rotation(g_warp_deg, g_warp_invx, g_warp_invy, g_warp_panx, g_warp_pany); /* re-apply -> LOD now live */
        }
#else
        xil_printf("UART: 'M' is warp-only; no warp engine in this build\r\n");
#endif
    } else if (op == 'K') {
        /* PROJECTIVE keystone: K <h> <v>  — symmetric H/V trapezoid. h,v are 1/1000 units of far-edge
         * shrink (so 'K 200 0' = 0.20 horizontal keystone, no vertical). 'K' alone = query. */
#ifdef PROJECTIVE_BUILD
        int h, v;
        if (parse_int(&p, &h)) {
            v = 0; parse_int(&p, &v);
            warp_set_keystone(h, v);
        } else {
            xil_printf("PROJ keystone h=%d.%03d v=%d.%03d\r\n",
                       g_proj_kh/1000, g_proj_kh%1000, g_proj_kv/1000, g_proj_kv%1000);
        }
#else
        xil_printf("UART: 'K' is projective-only; not a projective build\r\n");
#endif
    } else if (op == 'C') {
        /* PROJECTIVE corner-pin: C <x0> <y0> <x1> <y1> <x2> <y2> <x3> <y3>
         * The 8 args are the 4 SOURCE corners (in SOURCE pixels) that the 4 OUTPUT raster corners map to,
         * in TL,TR,BR,BL order (same quad order as tools/pg_projective_golden.py). e.g. an identity-ish pin
         * for a 1920x1080 source is 'C 0 0 1919 0 1919 1079 0 1079'. The engine inverse-maps output->source,
         * so these are exactly the source coords sampled at each output corner. 'C' alone = no-op note. */
#ifdef PROJECTIVE_BUILD
        int xi[4], yi[4]; int ok = 1;
        for (int k = 0; k < 4 && ok; k++) ok = parse_int(&p, &xi[k]) && parse_int(&p, &yi[k]);
        if (ok) {
            double sx[4], sy[4];
            for (int k = 0; k < 4; k++) { sx[k] = (double)xi[k]; sy[k] = (double)yi[k]; }
            if (warp_solve_cornerpin(sx, sy))
                xil_printf("PROJ cornerpin applied: TL(%d,%d) TR(%d,%d) BR(%d,%d) BL(%d,%d)\r\n",
                           xi[0],yi[0],xi[1],yi[1],xi[2],yi[2],xi[3],yi[3]);
            else
                xil_printf("PROJ cornerpin: degenerate corners, ignored\r\n");
        } else {
            xil_printf("UART: usage 'C x0 y0 x1 y1 x2 y2 x3 y3' (4 SOURCE corners TL,TR,BR,BL)\r\n");
        }
#else
        xil_printf("UART: 'C' is projective-only; not a projective build\r\n");
#endif
    } else if (op == 'G') {
        /* Route-B read-engine geometry (additive+mux build):
         *   G <w> <h> <sx> <sy> [a] — scale to w×h, SIGNED shift (sx,sy), anchor a
         *                             (a: 0=center [default], 1=top-left). sx<0/sy<0 push
         *                             the image off the left/top edge (pixels leave frame).
         *   G 0                     — passthrough (mux→VDMA MM2S, the boot default)
         *   G                       — re-emit / query current geometry
         * NO VDMA reconfig — just GPIO writes (contrast the reverted reframe). */
#ifdef GEO_A_BASE
        unsigned w, h, a; int x, y;
        if (parse_uint(&p, &w)) {
            if (w == 0) {
                g_re_engine = 0; re_write_geometry();
            } else if (parse_uint(&p, &h) && parse_int(&p, &x) && parse_int(&p, &y)) {
                g_re_w = w; g_re_h = h; g_re_x = x; g_re_y = y; g_re_engine = 1;
                if (parse_uint(&p, &a)) {                       /* optional anchor arg */
                    g_re_anchor = (a ? 1u : 0u);
                    if (parse_uint(&p, &a)) g_re_filt_mode = (a > 3u) ? 3u : a; /* optional filt-mode arg (#107) */
                }
                re_write_geometry();
            } else {
                xil_printf("UART: usage 'G w h sx sy [a [aa]]' (sx/sy signed) or 'G 0' (passthrough)\r\n");
            }
        } else {
            re_write_geometry();   /* query / re-emit */
        }
#else
        xil_printf("UART: read-engine geometry not present in this build\r\n");
#endif
    } else if (op == 'M') {
        /* Mackin blend toggle (read-engine):  M 1 = blend, M 0 = drop/repeat, M = query */
#ifdef GEO_A_BASE
        unsigned bv;
        if (parse_uint(&p, &bv)) { g_re_blend = (bv > 2u) ? 2u : bv; re_write_geometry(); }
        else xil_printf("UART: usage 'M 0|1|2' (0=off 1=intelligent 2=force); current blend=%u\r\n", g_re_blend);
#else
        xil_printf("UART: read-engine not present in this build\r\n");
#endif
    } else if (op == 'F') {
        /* read-side resample filter mode:  F 0=NN 1=2-tap box 2=H-bilinear 3=H+V-bilinear; F = query */
#ifdef GEO_A_BASE
        unsigned fv;
        if (parse_uint(&p, &fv)) { g_re_filt_mode = (fv > 3u) ? 3u : fv; re_write_geometry(); }
        else xil_printf("UART: usage 'F 0|1|2|3' (NN/box/H-bilin/H+V-bilin); current filt=%u\r\n", g_re_filt_mode);
#else
        xil_printf("UART: read-engine not present in this build\r\n");
#endif
    } else if (op == 'P') {
        /* fliP:  P h v   (h,v = 0/1) — horizontal / vertical flip (180 = P 1 1); P = query */
#ifdef GEO_A_BASE
        unsigned hf, vf;
        if (parse_uint(&p, &hf) && parse_uint(&p, &vf)) {
            g_re_hflip = (hf ? 1u : 0u); g_re_vflip = (vf ? 1u : 0u); re_write_geometry();
        } else xil_printf("UART: usage 'P h v' (flip); current hflip=%u vflip=%u\r\n", g_re_hflip, g_re_vflip);
#else
        xil_printf("UART: read-engine not present in this build\r\n");
#endif
    } else if (op == 'O') {
        /* Operator quick-actions (parity Phase 1):
         *   O m <0|1>          mono / grayscale
         *   O y <0|1>          proc-amp bypass (force identity)
         *   O k <0|1>          blackout (instant: 1=black, 0=restore)
         *   O t <K>            color-temp preset (3200/4800/5600/6500; 0/5600=neutral)
         *   O f <0-255> [step] fade white-point to target at <step>/frame (default 6) */
        unsigned v, st; char sub;
        while (*p == ' ' || *p == '\t') p++;
        sub = *p ? *p++ : 0;
        if      (sub == 'm' && parse_uint(&p, &v)) { g_mono   = v ? 1u : 0u; operator_apply(); }
        else if (sub == 'y' && parse_uint(&p, &v)) { g_bypass = v ? 1u : 0u; operator_apply(); }
        else if (sub == 'k' && parse_uint(&p, &v)) { g_fade_step = 0; g_fade_level = v ? 0u : 255u; g_fade_to = (int)g_fade_level; operator_apply(); }
        else if (sub == 't' && parse_uint(&p, &v)) { colortemp_preset(v); operator_apply(); }
        else if (sub == 'f' && parse_uint(&p, &v)) { g_fade_to = (v > 255u) ? 255 : (int)v; g_fade_step = parse_uint(&p, &st) ? (st ? st : 6u) : 6u; }
        else if (sub == 'z' && parse_uint(&p, &v)) {
            /* FREEZE: halt the S2MM writer (RS bit @ VDMA+0x30) -> frame_ptr holds -> read
             * engine reads the last completed slot = static frame (writer can't lap it).
             * UN-FREEZE: a halted VDMA channel does NOT restart on RS alone — the transfer
             * is re-triggered by (re)writing VSIZE @0x80. So re-arm with the saved VSIZE. */
            UINTPTR vb = XPAR_AXI_VDMA_0_BASEADDR;
            u32 cr = Xil_In32(vb + 0x30);
            if (v) {
                g_s2mm_vsize = Xil_In32(vb + 0x80);   /* save configured line count */
                Xil_Out32(vb + 0x30, cr & ~1u);       /* RS=0: halt */
                g_freeze = 1u;
            } else {
                Xil_Out32(vb + 0x30, cr | 1u);        /* RS=1: run */
                if (g_s2mm_vsize) Xil_Out32(vb + 0x80, g_s2mm_vsize); /* re-arm transfer */
                g_freeze = 0u;
            }
            xil_printf("FREEZE: %u (vsize=%u)\r\n", g_freeze, (unsigned)g_s2mm_vsize);
        }
        else if (sub == 'g' && parse_uint(&p, &v)) {
#ifdef GAMMA_GPIO_BASE
            gamma_load(v);   /* v = gamma*10 (continuous): 0/10=off, 18=1.8, 22=2.2, 23=2.3, ... */
#else
            xil_printf("UART: gamma LUT not present in this build\r\n");
#endif
        }
        else { xil_printf("UART: usage 'O m|y|k|z <0|1> | O t <K> | O g <gamma*10> | O f <0-255> [step]'\r\n"); }
        xil_printf("OP: mono=%u bypass=%u fade=%u->%u temp=%u gamma=%u\r\n", g_mono, g_bypass, g_fade_level, g_fade_to, g_colortemp, g_gamma);
    } else if (op == 'C') {
        /* input colorspace (parity 3.5). 'C r <0|1>' = range: 0=full (0-255),
         * 1=limited/studio (16-235 → expand to full via color_correct black/white).
         * YCbCr→RGB matrix decode is deferred (needs a YCbCr source to validate lane order). */
        char sub = 0; unsigned cv;
        while (*p == ' ' || *p == '\t') p++;
        sub = *p ? *p++ : 0;
        if (sub == 'r' && parse_uint(&p, &cv)) {
            if (cv) { g_black_r = g_black_g = g_black_b = 16; g_white_r = g_white_g = g_white_b = 235; g_range = 1; }
            else    { g_black_r = g_black_g = g_black_b = 0;  g_white_r = g_white_g = g_white_b = 255; g_range = 0; }
            operator_apply();
            xil_printf("CS: range=%s\r\n", cv ? "limited(16-235)" : "full(0-255)");
        } else {
            xil_printf("UART: usage 'C r 0|1' (range full/limited)\r\n");
        }
    } else {
        xil_printf("UART: unknown cmd '%s' — type ? for help\r\n", line);
    }
}

