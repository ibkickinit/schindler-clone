/* Per-geometry prefetch LEAD (pg_tilecache_rt2 run-ahead bound). The 4-way/512 cache deadlocks if the
 * prefetch runs far enough ahead to evict an unconsumed tile — too DEEP a lead for a gentle rotation is a
 * HARD FREEZE (this was the first-bench black screen). Bias SHALLOW for near-1:1 rotation (sim proved
 * lead<2048 is deadlock-free for ALL rotations) and DEEP only for downscale (concentrated reads don't
 * evict-deadlock even deep; 1.5x wants ~24576 to not underrun). Validated points (4-way/512,
 * sim/pg_warp_real_faithful_tb.v): rot20 safe<2048, rot45 ok, shrink1.5@24576, aniso@12288. 'L <n>'
 * overrides live at the bench. 20-bit. */
static unsigned warp_calc_lead(int deg, int invx, int invy)
{
    /* The prefetch must run far enough ahead to cover the tile-DMA round-trip or the consumer starves and
     * the frame comes up short (measured on silicon: identity @lead=1024 made only 762k/921600 px; @8192 it
     * makes the full frame). So the FLOOR is a throughput floor (~8192), NOT a shallow angle bias — the old
     * 1024..1744 heuristic was the shear/under-production cause. Downscale reads each tile many times -> goes
     * deeper. (Deep lead is fine for identity/gentle; steep-rotation eviction is re-checked on the good
     * timing build — the old "deep-lead deadlock" was the stale failed-timing bitstream.) */
    unsigned mx = (unsigned)(invx > invy ? invx : invy);
    int d180 = deg % 180; if (d180 < 0) d180 += 180;   /* 0 (and 180) = axis-aligned */
    /* DEEP lead (8192) for axis-aligned (0/180deg) zoom-in. ROTATIONS -> 4096 (2026-06-24): with the
     * 10deg-clamp + (1,33) cache hash, rotations no longer eviction-wedge at a deep lead (the hash spreads
     * the 2x2 working set so worst-set-live<=3 << 4-way at every supported angle), AND the deeper lead is
     * REQUIRED for the cardinal-transpose reads (90/270deg) and the near-cardinal band (40/220deg): at
     * shallow 1280 they STARVE (90deg eol 442; bench), at L=4096 every 10deg angle is FULL FRAME (verified
     * 30/40/90/130/160/20/70deg). So 4096 is the single rotation lead that covers transpose-starvation
     * without eviction. (Downscale mx>4096 still wants ~24576; deferred with scale<100%.) */
    /* DOWNSCALE (mx>4096, scale below whole-frame fit): SILICON-MEASURED lead (opix/frame sweep via the
     * live 'L' override, 2026-06-24). The cycle model (tools/warp_lod_throughput.py) MISPREDICTED the
     * direction — it does NOT capture the real demand-fetch/victim dynamics. On hardware:
     *   - fit 1.5x  : full frame (921600) needs lead >= 24576; a shorter lead STARVES (8192 -> 344k).
     *   - 2x (75%)  : best ~866k at lead 32768 (marginal, ~94%).
     *   - 3x (50%)  : STARVES at every lead (max ~770k/83% at 16384) -> genuine cache-CAPACITY wall;
     *                 only the half-res LOD mip (task #28, docs/lod-mip-design.md) makes 50% full.
     * 24576 keeps fit clean (the operating point); deeper downscale is the mip's job, not the lead's. */
    unsigned lead;
#if defined(RASTER_TO_TILE)
    /* TILED path (Path B dedicated-DMA, bench-measured 2026-06-25): the DEEP 24576 lead that the old
     * RASTER read path needed for downscale CATASTROPHICALLY STARVES the tiled read (it prefetches far
     * past the frame, thrashing the cache -> fit 1.5x = 82-126k/921600). The tiled path wants the SAME
     * ~8192 throughput-floor lead as identity. At lead=8192 on silicon:
     *   - single-axis downscale (H OR V alone): FULL FRAME to 2x  (V-2x and H-1.5x both = 921600).
     *   - uniform (both-axis) downscale: clean to ~1.4x (71%), marginal/teetering 1.5x-2x (combined
     *     H+V per-row tile span * tile-row count hits the genuine BW wall -> dest-res-master, task #28).
     * Tiling INVERTED the old asymmetry: vertical strides are now cheap (tile-row bursts), horizontal
     * width is the per-row cost. So one floor (8192) covers downscale, zoom-in, and identity here. */
    if (mx > 4096u)        lead = 8192u;    /* tiled downscale: 8192 floor (24576 overruns -> starve) */
    else if (d180 == 0)    lead = 8192u;    /* axis-aligned zoom-in / identity throughput floor */
    else                   lead = 4096u;    /* rotations: 10deg-clamp+(1,33) hash, covers transpose-starve */
#else
    if (mx > 4096u)        lead = 24576u;   /* RASTER downscale: deep lead -> fit (1.5x) full frame, silicon-verified */
    else if (d180 == 0)    lead = 8192u;    /* axis-aligned zoom-in / identity throughput floor */
    else                   lead = 4096u;    /* rotations: 10deg-clamp+(1,33) hash, covers transpose-starve */
#endif
    return lead > 0x000FFFFFu ? 0x000FFFFFu : lead;
}

