/* ==========================================================================
 * PROJECTIVE coeff regime (FB=20 numerator / GFB=36 perspective). One writer
 * for ALL geometry: warp_apply_homography(a..f, g, h). Rotation / zoom / pan
 * are the affine sub-case (g=h=0). Keystone / corner-pin solve a full
 * homography. Inputs are the ALREADY-quantized fixed-point ints:
 *   a..f : signed Q12.20 (== floor(coeff * 2^20)), written to GEO_A/B/C GPIOs (low 32 bits, like affine)
 *   g,h  : signed Q4.36  (== floor(coeff * 2^36)), 40-bit each -> split low32+high8 across GH_LO/GH_HI
 * The engine inverse-maps OUTPUT->SOURCE: src = (a*ox + b*oy + c) / w,  w = g*ox + h*oy + 1.
 *
 * !! CW=32 PORT FIT: the a..f GPIO ports are 32 bits, so each coeff must fit signed-32. FB was 24 (Q8.24)
 * through P1-P4, which gave only +/-128 SOURCE-PIXELS of range -> the translation coeffs c (=src_x at
 * output origin) and f (=src_y) are ~hundreds of px at 1080p (even identity ~320 px) and OVERFLOWED,
 * warping to the wrong source origin on silicon. FB=20 (Q12.20) gives +/-2048 px, covering the 1920-px
 * source (max|a..f_q| ~2^28.5 for strong keystone). The precision cost is Q.13 -> Q.8.5 worst-case at the
 * most-foreshortened keystone corner (~2.7e-3 px), visually lossless. See docs/projective-fb-fix.md. */
typedef long long q20_t;   /* Q12.20 intermediate (64-bit so products don't overflow before the >>20) */

static void gh_write40(u32 base, long long g36, long long h36)
{
    /* g36/h36 are signed Q4.36; write the low 32 + high 8 to the two channels of the GH GPIO pair. */
#if defined(GH_LO_BASE) && defined(GH_HI_BASE)
    u32 g_lo = (u32)((unsigned long long)g36 & 0xFFFFFFFFull);
    u32 h_lo = (u32)((unsigned long long)h36 & 0xFFFFFFFFull);
    u32 g_hi = (u32)(((unsigned long long)g36 >> 32) & 0xFFu);
    u32 h_hi = (u32)(((unsigned long long)h36 >> 32) & 0xFFu);
    Xil_Out32(GH_LO_BASE + 0x00, g_lo);   /* axi_gpio_13 ch1 = m_g[31:0]  */
    Xil_Out32(GH_LO_BASE + 0x08, h_lo);   /* axi_gpio_13 ch2 = m_h[31:0]  */
    Xil_Out32(GH_HI_BASE + 0x00, g_hi);   /* axi_gpio_14 ch1 = m_g[39:32] */
    Xil_Out32(GH_HI_BASE + 0x08, h_hi);   /* axi_gpio_14 ch2 = m_h[39:32] */
    (void)base;
#else
    (void)base; (void)g36; (void)h36;
#endif
}

/* Apply a homography given pre-quantized coeffs: a..f Q12.20, g/h Q4.36. Writes ALL geometry GPIOs and
 * pulses the soft-reset (same flush sequence as affine warp_set_rotation). g=h=0 -> pure affine. */
static void warp_apply_homography(int a20,int b20,int c20,int d20,int e20,int f20,
                                  long long g36,long long h36, unsigned lead)
{
    Xil_Out32(GEO_A_BASE + 0x00, (u32)a20);   /* m_a */
    Xil_Out32(GEO_A_BASE + 0x08, (u32)b20);   /* m_b */
    Xil_Out32(GEO_B_BASE + 0x00, (u32)c20);   /* m_c */
    Xil_Out32(GEO_B_BASE + 0x08, (u32)d20);   /* m_d */
    Xil_Out32(GEO_C_BASE + 0x00, (u32)e20);   /* m_e */
    Xil_Out32(GEO_C_BASE + 0x08, (u32)f20);   /* m_f */
    gh_write40(0, g36, h36);
#ifdef LEAD_GPIO_BASE
    g_warp_lead = lead;
    u32 ldw = (g_warp_lead & 0xFFFFFu);
    Xil_Out32(LEAD_GPIO_BASE, ldw);
    /* soft-reset pulse (lead_cfg[31]) -> clean cache start on the new geometry, no transition wedge. */
    Xil_Out32(LEAD_GPIO_BASE, (1u << 31) | ldw);
    for (volatile int d = 0; d < 30000; d++) { }
    Xil_Out32(LEAD_GPIO_BASE, ldw);
#else
    (void)lead;
#endif
}

/* float -> signed Q12.20 (floor), matching the golden's to_q(). The CPU does this once per geometry
 * change (cheap, like the gamma-curve compute), so float on the A9 is fine. */
static int to_q20(double v)  { return (int)llround_floor(v * 1048576.0); }      /* 2^20 */
static long long to_q36(double v) { return (long long)llround_floor(v * 68719476736.0); } /* 2^36 */

/* 4-point homography solver. Maps OUTPUT corners (dst) -> SOURCE corners (src) — the engine inverse-maps
 * output->source, so H * [ox,oy,1]^T ~ [sx,sy,1]^T. Mirrors tools/pg_projective_golden.py solve_homography
 * EXACTLY (same 8x8 DLT, same row ordering, i normalized to 1). dst is the full output raster corners;
 * src[] are the 4 source-space corners (TL,TR,BR,BL order). Writes the engine via warp_apply_homography. */
static int warp_solve_cornerpin(const double sx[4], const double sy[4])
{
    /* output (dst) corners, full raster, TL,TR,BR,BL — same as the golden's dst quad. */
    const double ox[4] = {0.0, (double)(OUT_RASTER_W-1), (double)(OUT_RASTER_W-1), 0.0};
    const double oy[4] = {0.0, 0.0, (double)(OUT_RASTER_H-1), (double)(OUT_RASTER_H-1)};
    /* Build the 8x8 system A*[a b c d e f g h]^T = B  (rows per the golden):
     *   row 2k  : [ox oy 1 0 0 0 -ox*sx -oy*sx] = sx
     *   row 2k+1: [0 0 0 ox oy 1 -ox*sy -oy*sy] = sy   */
    double M[8][9];
    for (int k = 0; k < 4; k++) {
        double X = ox[k], Y = oy[k], SX = sx[k], SY = sy[k];
        double *r0 = M[2*k], *r1 = M[2*k+1];
        r0[0]=X; r0[1]=Y; r0[2]=1; r0[3]=0; r0[4]=0; r0[5]=0; r0[6]=-X*SX; r0[7]=-Y*SX; r0[8]=SX;
        r1[0]=0; r1[1]=0; r1[2]=0; r1[3]=X; r1[4]=Y; r1[5]=1; r1[6]=-X*SY; r1[7]=-Y*SY; r1[8]=SY;
    }
    /* Gaussian elimination with partial pivoting (mirrors the golden). */
    for (int col = 0; col < 8; col++) {
        int piv = col; double best = (M[col][col] < 0 ? -M[col][col] : M[col][col]);
        for (int r = col+1; r < 8; r++) {
            double av = (M[r][col] < 0 ? -M[r][col] : M[r][col]);
            if (av > best) { best = av; piv = r; }
        }
        if (best < 1e-12) return 0;                    /* singular / degenerate corners */
        if (piv != col) { for (int j=0;j<9;j++){ double t=M[col][j]; M[col][j]=M[piv][j]; M[piv][j]=t; } }
        double pv = M[col][col];
        for (int j = col; j < 9; j++) M[col][j] /= pv;
        for (int r = 0; r < 8; r++) {
            if (r != col && M[r][col] != 0.0) {
                double fac = M[r][col];
                for (int j = col; j < 9; j++) M[r][j] -= fac * M[col][j];
            }
        }
    }
    double a=M[0][8],b=M[1][8],c=M[2][8],d=M[3][8],e=M[4][8],f=M[5][8],g=M[6][8],h=M[7][8];
    /* LEAD must track the DOWNSCALE this quad implies. A source quad BIGGER than the output raster (e.g. the
     * whole-frame 1920×1080 identity into 720p = 1.5×) re-reads each tile across many rows and UNDERRUNS at a
     * shallow lead -> scramble (bench 2026-06-24: factory-reset cornerpin landed at fit with the old hardcoded
     * 8192 and scrambled; a warp.set at the same 1.5× with warp_calc_lead's 24576 was clean). Estimate the
     * max downscale from the quad's source extent and reuse the affine lead heuristic so cornerpin + keystone
     * get the SAME deep lead as warp.set at the same shrink. */
    double sw_top = sx[1]-sx[0], sw_bot = sx[2]-sx[3];   /* top / bottom edge widths  */
    double sh_lft = sy[3]-sy[0], sh_rgt = sy[2]-sy[1];   /* left / right edge heights */
    double src_w  = (sw_top > sw_bot ? sw_top : sw_bot); if (src_w < 0) src_w = -src_w;
    double src_h  = (sh_lft > sh_rgt ? sh_lft : sh_rgt); if (src_h < 0) src_h = -src_h;
    double rx = src_w / (double)OUT_RASTER_W, ry = src_h / (double)OUT_RASTER_H;
    double ratio = (rx > ry ? rx : ry);
    int invx_eq = (int)(ratio * 4096.0 + 0.5);           /* affine-equivalent inverse-scale */
    unsigned lead = warp_calc_lead(0, invx_eq, invx_eq); /* deep for >1.0× shrink, like warp.set */
    /* LOD: fetch from a mip so the cache sees effective <=1.5x (silicon-clean). L0<=1.5x, L1<=3x, else L2. */
    g_warp_lod = (invx_eq <= 6144) ? 0u : (invx_eq <= 12288) ? 1u : 2u;
    warp_apply_homography(to_q20(a),to_q20(b),to_q20(c),to_q20(d),to_q20(e),to_q20(f),
                          to_q36(g),to_q36(h), lead);
    xil_printf("PROJ cornerpin: a=%dE-6 c=%d f=%d (q20) g/h=Q36\r\n",
               (int)(a*1000000), to_q20(c), to_q20(f));
    return 1;
}

/* SIGNED H/V keystone -> 4 source corners -> cornerpin solver. h_amt/v_amt are PERCENT*10 of the far-edge
 * shrink, now SIGNED (so '200' = +0.20, '-200' = -0.20).
 *   H keystone: +h shrinks the TOP edge width (top-narrow trapezoid); -h shrinks the BOTTOM edge width.
 *   V keystone: +v shrinks the LEFT edge height (left-short trapezoid); -v shrinks the RIGHT edge height.
 * The V axis is a REAL trapezoid (left/right edge heights differ) — the old formula moved BOTH top corners
 * together, which is a uniform vertical SCALE, not a keystone (bench 2026-06-24: "+V just stretches taller").
 * sw/sh = 0.5 so the h=v=0 identity is the FULL 1920×1080 raster = whole-frame fit (consistent with scale
 * 100% / cornerpin identity). Both axes compose (H drives sx, V drives sy). */
static void warp_set_keystone(int h_amt_e3, int v_amt_e3)
{
    double h = h_amt_e3 / 1000.0, v = v_amt_e3 / 1000.0;
    if (h < -0.9) h = -0.9; if (h > 0.9) h = 0.9;
    if (v < -0.9) v = -0.9; if (v > 0.9) v = 0.9;
    /* half-extents about center use FRAME-1 so the h=v=0 identity corners are exactly (0,0)..(1919,1079),
     * matching the cornerpin full-raster identity (no off-by-one source-edge matte line). */
    double mx = (FRAME_W - 1) * 0.5, my = (FRAME_H - 1) * 0.5;
    double sw = (FRAME_W - 1) * 0.5, sh = (FRAME_H - 1) * 0.5;
    double ht = h > 0 ? h : 0.0, hb = h < 0 ? -h : 0.0;   /* H: top vs bottom edge shrink */
    double vl = v > 0 ? v : 0.0, vr = v < 0 ? -v : 0.0;   /* V: left vs right edge shrink */
    /* TL,TR,BR,BL. sx: top edge (TL,TR) shrunk by ht, bottom edge (BL,BR) by hb.
     *               sy: left edge (TL,BL) shrunk by vl, right edge (TR,BR) by vr. */
    double sx[4] = { mx - sw*(1.0-ht), mx + sw*(1.0-ht), mx + sw*(1.0-hb), mx - sw*(1.0-hb) };
    double sy[4] = { my - sh*(1.0-vl), my - sh*(1.0-vr), my + sh*(1.0-vr), my + sh*(1.0-vl) };
    g_proj_kh = h_amt_e3; g_proj_kv = v_amt_e3;
    if (!warp_solve_cornerpin(sx, sy))
        xil_printf("PROJ keystone: degenerate, ignored\r\n");
    else
        xil_printf("PROJ keystone h=%d.%03d v=%d.%03d applied\r\n",
                   h_amt_e3/1000, h_amt_e3%1000, v_amt_e3/1000, v_amt_e3%1000);
}
#endif /* PROJECTIVE_BUILD */

/* Compute + write the 6 affine coeffs for rotation `deg` with inverse-scale
 * invx/invy (Q12; 4096 = 1.0 source-px per output-px, >4096 = downscale). */
static void warp_set_rotation(int deg, int invx, int invy, int panx, int pany)
{
    /* 2026-06-24 ROTATION CLAMP -> 10-degree increments. Continuous rotation overflows the 4-way tile
     * cache at narrow angle bands for ANY set-index hash (exhaustively offline-proven 1-179deg; bench-
     * confirmed 13,7 fails ~17-19, 5,59 fails ~90+125-140). The (1,33) hash in pg_tilecache_rt2 is
     * bench-clean ONLY on the 10-deg grid {0,10,...,350}, where worst-set-live<=3 fits 4-way with no
     * eviction. Snap the requested angle to the nearest 10deg so off-grid angles can't thrash the cache. */
    { int m = deg % 360; if (m < 0) m += 360; m = ((m + 5) / 10) * 10; if (m >= 360) m -= 360; deg = m; }
    int co = warp_cos(deg), si = warp_sin(deg);          /* Q12 */
    int cxo = (int)g_out_w / 2, cyo = (int)g_out_h / 2;   /* output center = runtime VTC raster */
    /* DYNAMIC RING: source center = the runtime LOD center, so a sub-LOD maps
     * its center to the output center = auto-centered. At 100% g_lod = OUT_RASTER
     * so this is the old FRAME/2 (bit-identical). */
    int cxs = (int)g_lod_w / 2, cys = (int)g_lod_h / 2;   /* source center = LOD center */
    int m_a =  (int)(((long long)co * invx) >> 12);
    int m_b =  (int)(((long long)si * invx) >> 12);
    int m_d = -(int)(((long long)si * invy) >> 12);
    int m_e =  (int)(((long long)co * invy) >> 12);
    /* Translation = where output (0,0) maps in source. CENTER anchor (default): output-center maps to
     * source-center, so zoom/rotation pivot about the middle. TOP-LEFT anchor: output (0,0) maps to the
     * identity top-left source point (the center-crop origin (FRAME-OUT)/2), so zoom/rotation pivot about
     * the top-left corner and the image grows toward bottom-right. At identity (m_a=4096) both give the
     * same 1:1 center crop; they only differ once invx/invy or deg move. */
    int m_c, m_f;
    if (g_warp_anchor) {
        /* TOP-LEFT anchor: fix output(0,0) -> source(0,0) = the whole-frame identity's top-left corner.
         * (Under the whole-frame-fit "100%" model the image origin is source 0,0, NOT the old center-crop
         * origin 320,180 — that stale offset made the anchor shift the image by ~212,119 output px.) At the
         * fit baseline this equals the center anchor (both -> source 0,0); they only diverge under zoom. */
        m_c = 0;
        m_f = 0;
    } else {
        m_c = cxs * 4096 - m_a * cxo - m_b * cyo;
        m_f = cys * 4096 - m_d * cxo - m_e * cyo;
    }
    /* PAN (Shift X/Y): move the image by (panx,pany) OUTPUT px on screen. Applied THROUGH the affine
     * (subtract the shift from the output coord before mapping) so it stays SCREEN-space at any
     * rotation/zoom; the image leaves the frame and matte fills the opposite edge. +panx = image right. */
    m_c -= m_a * panx + m_b * pany;
    m_f -= m_d * panx + m_e * pany;
    g_warp_deg = deg; g_warp_invx = invx; g_warp_invy = invy; g_warp_panx = panx; g_warp_pany = pany;
    unsigned lead = g_warp_lead_ovr ? g_warp_lead_ovr : warp_calc_lead(deg, invx, invy);
    /* LOD select from the shrink factor (max inverse-scale). L0<=1.5x (mx<=6144), L1<=3x (<=12288), else L2.
     * The HDL shifts the source coord >>L and fetches the pre-shrunk mip so the cache sees effective <=1.5x. */
    { unsigned mxl = (unsigned)(invx > invy ? invx : invy);
      g_warp_lod = (mxl <= 6144u) ? 0u : (mxl <= 12288u) ? 1u : 2u; }
#ifdef PROJECTIVE_BUILD
    /* PROJECTIVE build: the engine numerator is Q12.20 (FB=20), not Q.12. Rotation/zoom/pan are the affine
     * sub-case (g=h=0). m_a..m_e here are co/si*invx >> 12 = Q.12 ratios; shift them << 8 to Q.20. The
     * translation m_c/m_f were built as src_center*4096 (Q.12) so they also become Q.20 with << 8. Route
     * through the single homography writer so rotation and keystone share one coeff path + one g/h packing. */
    warp_apply_homography((int)((long long)m_a << 8), (int)((long long)m_b << 8),
                          (int)((long long)m_c << 8), (int)((long long)m_d << 8),
                          (int)((long long)m_e << 8), (int)((long long)m_f << 8),
                          0, 0, lead);
    g_proj_kh = 0; g_proj_kv = 0;   /* rotation cancels any prior keystone */
#else
    Xil_Out32(GEO_A_BASE + 0x00, (u32)m_a);
    Xil_Out32(GEO_A_BASE + 0x08, (u32)m_b);
    Xil_Out32(GEO_B_BASE + 0x00, (u32)m_c);
    Xil_Out32(GEO_B_BASE + 0x08, (u32)m_d);
    Xil_Out32(GEO_C_BASE + 0x00, (u32)m_e);
    Xil_Out32(GEO_C_BASE + 0x08, (u32)m_f);
    /* set the prefetch LEAD for this geometry (manual override wins). Takes effect at the next sof
     * (lead_cnt resets there), same vblank the new coeffs latch. */
#ifdef LEAD_GPIO_BASE
    g_warp_lead = lead;
    Xil_Out32(LEAD_GPIO_BASE, g_warp_lead);
    /* Pulse the engine SOFT-RESET (lead_cfg[31]) AFTER the coeffs+lead are written: it clears the warp
     * engine + tile-cache + cmd formatter + output FIFO and FLUSHes the DataMover's in-flight beats, so the
     * cache starts clean on the new geometry -> NO transition wedge. The next sof restarts the walk with the
     * new coeffs. Held briefly (~150us, well under a frame); the flush self-completes after deassert. */
    Xil_Out32(LEAD_GPIO_BASE, (1u << 31) | (g_warp_lead & 0xFFFFFu));
    for (volatile int d = 0; d < 30000; d++) { }
    Xil_Out32(LEAD_GPIO_BASE, g_warp_lead & 0xFFFFFu);
#endif
#endif /* PROJECTIVE_BUILD */
    xil_printf("WARP rot=%d invx=%d invy=%d lead=%u: a=%d b=%d c=%d d=%d e=%d f=%d\r\n",
               deg, invx, invy, (unsigned)g_warp_lead, m_a, m_b, m_c, m_d, m_e, m_f);
}

/* ============================================================================
 * DECIMATE-ON-WRITE scale (D2/D3, 2026-06-25) — the unified user "scale" knob.
 *
 * Keeps downscale OFF the warp read (the bandwidth wall) by moving it to the
 * scaler's WRITE-side decimation, and keeps upscale on the warp's zoom-in:
 *   pct >= 100 : scaler emits the FULL OUT_RASTER LOD, S2MM full-frame, the
 *                warp ZOOMS in (invx=invy=4096*100/pct). 100% == the proven
 *                clean pivot (137b13d).
 *   pct <  100 : the scaler DECIMATES the source to a small raster (G1
 *                out_w/out_h GPIO); the S2MM writes it as a top-left SUB-WINDOW
 *                of the fixed OUT_RASTER frame (Stride stays full pitch); the
 *                ring is pre-cleared to matte so the border reads clean; the
 *                warp stays at IDENTITY (no downscale-fetch -> no starve). Deep
 *                decimation (<=67%) switches the scaler to 4-tap (averages).
 * The warp source frame stays FIXED at OUT_RASTER ("LOD == output res, never
 * switched within an engine") so NO warp address-math is runtime. Auto-center
 * of the sub-window is a follow-up (user pans via 'W' for now).
 * ==========================================================================*/

/* ch2 of axi_gpio_1 (base+0x08): [15:0]=OUT_W, [31:16]=OUT_H -> scaler
 * out_w/h_async = the G1 runtime DDA step (decimation target). */
static inline void scaler_out_dims_write(u32 out_w, u32 out_h)
{
    u32 v = ((out_h & 0xFFFFu) << 16) | (out_w & 0xFFFFu);
    Xil_Out32(SCALER_DIMS_GPIO_BASEADDR + 0x08, v);
}

/* Pre-clear all NUM_FRAMES ring slots' frame region to matte (0x10/byte =
 * 0x101010, the warp's out-of-window matte) so a sub-window write leaves a
 * clean border. Flush to DDR for the warp DataMover. Only on a scale change. */
static void ring_clear_matte(void) __attribute__((unused));
static void ring_clear_matte(void)
{
    const UINTPTR SLOT_BYTES = (UINTPTR)FRAME_BYTES + (UINTPTR)STRIDE;
    int i;
    for (i = 0; i < NUM_FRAMES; i++) {
        void *f = (void *)(uintptr_t)(FRAME_BUF_BASE + (UINTPTR)i * SLOT_BYTES);
        memset(f, 0x10, FRAME_BYTES);
    }
    Xil_DCacheFlushRange((INTPTR)FRAME_BUF_BASE, (UINTPTR)NUM_FRAMES * SLOT_BYTES);
}

/* DYNAMIC RING (2026-06-26): set the S2MM write geometry to a COMPACT out_w x
 * out_h LOD (stride = out_w*3, NOT the full frame pitch). The read engine reads
 * the same compact LOD natively (its in_w_rt drives the matching read stride),
 * and the warp PLACES the LOD centered in the output with its own out-of-window
 * matte -> no DDR matte, no padding. out_w==OUT_RASTER_W && out_h==OUT_RASTER_H
 * is the full 1:1 frame.
 *
 * CRITICAL: update ONLY the geometry registers (HSIZE / STRD_FRMDLY / VSIZE)
 * directly, leaving S2MM_DMACR (RS, dynamic-genlock, external-fsync) UNTOUCHED.
 * The driver's DmaStop+DmaConfig rewrites DMACR + halts -> broke genlock/fsync
 * -> black (bench-confirmed). PG020 register-direct resize: HSIZE + STRIDE,
 * then VSIZE LAST (commit); the running channel adopts it at the next fsync. */
static int s2mm_set_geometry(u32 out_w, u32 out_h)
{
    const UINTPTR S2MM = XPAR_AXI_VDMA_0_BASEADDR + 0xA0u; /* S2MM reg-direct block base */
    Xil_Out32(S2MM + 0x04u, out_w * BYTES_PP);   /* HSIZE = valid bytes/line        */
    Xil_Out32(S2MM + 0x08u, out_w * BYTES_PP);   /* STRD_FRMDLY: COMPACT stride, frmdly=0 */
    Xil_Out32(S2MM + 0x00u, out_h);              /* VSIZE LAST -> commits geometry  */
    return XST_SUCCESS;
}

static unsigned g_scale_pct = 100;   /* unified user scale; 100 = 1:1 whole image */

/* Pick the scaler kernel from the ACTUAL decimation ratio (src/lod), not pct, so
 * a 1:1 ratio is a BIT-EXACT passthrough. The scaler's 2-tap boxcar averages
 * neighbors even at 1:1 (a slight blur); NN (mode 0) at >=1:1 passes the source
 * pixel through unchanged. Only a real downscale needs the anti-alias filter.
 *   lod >= src      -> NN (mode 0): bit-exact at 1:1 / blocky upscale
 *   src <= 2x lod    -> 2-tap (mode 1): correct box for up to 2x downscale
 *   src >  2x lod    -> 4-tap (mode 2): deep downscale anti-alias */
static void scaler_kernel_for_ratio(u32 lod_w, u32 lod_h)
{
#ifdef SCALER_KERNEL_GPIO_BASEADDR
    unsigned sw = g_src_hactive ? g_src_hactive : OUT_RASTER_W;
    unsigned sh = g_src_vactive ? g_src_vactive : OUT_RASTER_H;
    unsigned kh = (lod_w >= sw) ? 0u : ((lod_w * 2u >= sw) ? 1u : 2u);
    unsigned kv = (lod_h >= sh) ? 0u : ((lod_h * 2u >= sh) ? 1u : 2u);
    Xil_Out32(SCALER_KERNEL_GPIO_BASEADDR, (kv << 2) | kh);
#else
    (void)lod_w; (void)lod_h;
#endif
}

static void apply_scale(unsigned pct)
{
    if (pct < 10u)  pct = 10u;
    if (pct > 200u) pct = 200u;
    g_scale_pct = pct;

    /* DYNAMIC RING model: the LOD = scaler out = S2MM compact write = warp
     * source (in_w_rt, via the shared GPIO). The warp reads the native LOD and
     * PLACES it centered (source-center = g_lod/2); its out-of-window matte
     * fills the border. No DDR matte, no padding, no clear race. */
    if (pct >= 100u) {
        /* UPSCALE / 100%: full LOD (= OUT_RASTER). OVER-RES (2026-06-26): the LOD
         * HEIGHT is the EXACT output height (even-aligned), NOT floored to /16 —
         * so a 1080 output keeps all 1080 rows (was 1072, an 8-row bottom strip).
         * The warp grid is built one band taller (ceil, RE_IN_H=1088) so band 67
         * is addressable; its over-read past the content is clamped out of view.
         * Width stays /16 (stride/tile alignment; 1920/1280 already /16). */
        g_lod_w = g_out_w & ~15u; g_lod_h = g_out_h & ~1u;   /* LOD MAX = runtime output raster */
        scaler_kernel_for_ratio(g_lod_w, g_lod_h);   /* NN if 1:1 (bit-exact); filter if downscaling */
        s2mm_set_geometry(g_lod_w, g_lod_h);            /* full compact == full frame          */
        scaler_out_dims_write(g_lod_w, g_lod_h);        /* also drives warp in_w_rt (tied GPIO) */
        int inv = (int)((4096u * 100u) / pct);          /* 100->4096(1:1), 200->2048(2x)        */
        warp_set_rotation(g_warp_deg, inv, inv, g_warp_panx, g_warp_pany);
        xil_printf("SCALE %u%%: LOD %ux%u, warp zoom inv=%d\r\n", pct, g_lod_w, g_lod_h, inv);
    } else {
        /* DOWNSCALE: scaler decimates to a compact LOD; warp reads it 1:1 and
         * auto-centers. Snap dims to /16 so the tile grid covers the LOD with no
         * partial-tile over-read (the 8-row crop at e.g. 360->352 is invisible). */
        u32 ow = ((g_out_w * pct) / 100u) & ~15u;   /* width /16 (stride/tile align); rel. runtime output */
        u32 oh = ((g_out_h * pct) / 100u) & ~1u;    /* OVER-RES: exact even height, no /16 floor */
        if (ow < 16u) ow = 16u;
        if (oh < 16u) oh = 16u;
        g_lod_w = ow; g_lod_h = oh;
        scaler_kernel_for_ratio(ow, oh);   /* ratio-based: 1:1 NN, <=2x 2-tap, >2x 4-tap */
        s2mm_set_geometry(ow, oh);           /* S2MM writes the compact LOD                 */
        scaler_out_dims_write(ow, oh);       /* scaler decimates + drives warp in_w_rt       */
        /* warp identity: source-center (ow/2,oh/2) -> output center = auto-centered.
         * out-of-window matte fills the border; no DDR matte / clear needed. */
        warp_set_rotation(g_warp_deg, 4096, 4096, g_warp_panx, g_warp_pany);
#ifdef SCALER_KERNEL_GPIO_BASEADDR
        u32 kreg = Xil_In32(SCALER_KERNEL_GPIO_BASEADDR);
        static const char *kname[3] = {"NN", "2tap", "4tap"};
        xil_printf("SCALE %u%%: LOD %ux%u centered (compact), warp identity, kH=%s kV=%s\r\n",
                   pct, (unsigned)ow, (unsigned)oh, kname[kreg & 3u], kname[(kreg >> 2) & 3u]);
#else
        xil_printf("SCALE %u%%: LOD %ux%u centered (compact), warp identity\r\n",
                   pct, (unsigned)ow, (unsigned)oh);
#endif
    }
}
#endif /* WARP_BUILD */

/* Phase-3 gamma/tone LUT load GPIO (axi_gpio_11): bit0=bypass, bit1=tog,
 * [3:2]=ch, [11:4]=addr, [19:12]=data. See gamma_lut.v / readengine_b_bd.tcl. */
