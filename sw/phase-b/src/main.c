/* AXIS data width on the VDMA is 24-bit (RGB888, one pixel-per-clock with no
 * padding). Memory stride must therefore be 3 bytes/pixel, NOT 4 — using 4
 * was the actual reason v_axi4s_vid_out couldn't lock and S2MM was reporting
 * EOLEarly/EOLLate framing errors. Confirmed via UART diag dumps. */
#define BYTES_PP          3
#define STRIDE            (FRAME_W * BYTES_PP)
#define FRAME_BYTES       (STRIDE * FRAME_H)

/* ---- Path B (TILED DataMover) S2MM layout --------------------------------------------------------------
 * RASTER_TO_TILE=1: pg_raster_to_tile (on the S2MM write leg) converts the source raster into a contiguous
 * TILE-ROW-MAJOR stream of 16x16 tiles (each tile = 256 px = 768 bytes), with AXIS tlast on the LAST beat of
 * every tile.  The warp read engine (pg_tile_dma TILED) then fetches one 768B burst per tile from
 *     tile (ty,tx) -> frame_base + (ty*TILES_X + tx) * TILE_BYTES.
 *
 * To make the DDR bytes land at exactly those addresses, the S2MM must store the AXIS stream CONTIGUOUSLY at
 * the slot base.  The VDMA S2MM is a 2D engine (HSIZE bytes/line, Stride between lines, VSIZE lines) that
 * advances one "line" per AXIS tlast.  Since pg_raster_to_tile asserts tlast once per 768-byte tile, we map
 * ONE S2MM "line" == ONE tile:
 *     HoriSizeInput = TILE_BYTES (768)           — bytes written per tlast
 *     Stride        = TILE_BYTES (768)           — == HSIZE  => fully contiguous, no inter-line gap
 *     VertSizeInput = TILES_X * TILES_Y          — total tiles per frame
 * Result: tile k (= ty*TILES_X+tx, the emit order) lands at slot_base + k*768.  This is bit-identical to
 * pg_tile_dma's TILED read address (verified by sim pg_raster_to_tile_tb + pg_tile_dma_tiled_tb sharing the
 * (ty*TILES_X+tx)*768 / (r*16+c)*3 contract).  Total bytes/frame = TILES_X*TILES_Y*768 (see below) <=
 * the existing SLOT_STRIDE, so the slot ring (FRAME_BUF_BASE + slot*SLOT_STRIDE) and genlock are UNCHANGED.
 *
 * 1080 is NOT a multiple of 16 (1080/16 = 67.5).  pg_raster_to_tile only emits COMPLETE 16-row bands, so it
 * stores TILES_Y = floor(1080/16) = 67 tile-rows (source rows 0..1071) and drops the trailing 8-row band.
 * VSIZE must therefore be TILES_X*67 (= the actual tile-tlast count/frame), and pg_re_0 is built with
 * IN_H=1072 so the read engine never requests ty>66.  The bottom 8 source rows are cropped (cosmetic ~5
 * output rows of matte after the 1.5x fit-downscale).  Padding to 1088 (full height) is deferred — it needs
 * a partial-band-flush path in pg_raster_to_tile that is not yet sim-covered.
 *
 * TILES_X uses IN_W (1920, divisible by 16) regardless of the build's FRAME_W, because the tile grid width is
 * fixed by the 1920-wide DDR master that the warp engine reads. */
#define TILE_PX           16
#define TILE_BYTES        (TILE_PX * TILE_PX * BYTES_PP)   /* 768 */
/* Tile grid = the DDR master (= the LOD under dest-res). Derive from FRAME_W/H so it follows the LOD:
 *   dest-res LOD 1280x720 -> 80 x 45 (720 is a clean multiple of 16, NO partial-band crop).
 *   legacy full-master 1920x1080 -> 120 x 67 (integer div floors the trailing 8-row band, as before). */
#define TILES_X_FULL      (FRAME_W / TILE_PX)              /* LOD:80  full:120 */
#define TILES_Y_FULL      (FRAME_H / TILE_PX)              /* LOD:45  full:67(floor) */
#define TILED_FRAME_TILES (TILES_X_FULL * TILES_Y_FULL)    /* 8040 (== VDMA VSIZE, < 8191 reg max) */
#define TILED_FRAME_BYTES (TILED_FRAME_TILES * TILE_BYTES) /* 6,174,720  (<= FRAME_BYTES 6,220,800) */
/* iter5-bisect-720p: NUM_FRAMES 5 → 3 to isolate scroll cause. Bisect shows
 * 5 framestores is the only iter5 substrate change vs. clean iter4h; revert
 * to 3 to confirm. BD config c_num_fstores must also match (3 in TCL). */
/* iter5-1080p-clean: NUM_FRAMES 3 → 5 to give S2MM enough cycle headroom
 * to not lap MM2S during its 41.7 ms read window at 24p output. 5 × 16.7
 * = 83 ms cycle time vs. MM2S 41.7 ms read = 2× headroom. Addresses the
 * FRC tear-line-that-drifts symptom. BD c_num_fstores must match. */
#define NUM_FRAMES        7   /* #28: 5->7 (MUST == VDMA c_num_fstores) so cadence lag reaches 2 for Mackin blend. 7*SLOT_STRIDE=43.6MB from FRAME_BUF_BASE. */
#define FRAME_BUF_BASE    0x10000000U

static XAxiVdma vdma;
static XVtc    vtc;

static int vdma_setup_channel(int direction, UINTPTR *frame_addrs)
{
    XAxiVdma_DmaSetup cfg;
    int status;

    /* iter5-bisect FINAL (2026-05-17 evening): both channels VSIZE = FRAME_H.
     * Pure iter4d-3 substrate. Production-clean visually at matched rate
     * with laptop source. Bottom-bars artifact (if it reappears with other
     * sources) will need a non-over-allocate fix. */
    cfg.VertSizeInput     = FRAME_H;
    cfg.HoriSizeInput     = STRIDE;
    cfg.Stride            = STRIDE;
#if defined(RASTER_TO_TILE)
    /* Path B: S2MM stores the contiguous tile-row-major stream (1 S2MM "line" == 1 tile). See the
     * TILE_BYTES / TILED_FRAME_* block above for the full layout reasoning. The MM2S leg is unused on this
     * path (the warp engine reads via its own DataMover), so it gets the same tiled geometry harmlessly. */
    cfg.VertSizeInput = TILED_FRAME_TILES;   /* 8040 tiles/frame                    */
    cfg.HoriSizeInput = TILE_BYTES;          /* 768 valid bytes per tlast (1 tile)  */
    cfg.Stride        = TILE_BYTES;          /* == HSIZE => fully contiguous in DDR  */
#elif defined(READENGINE_FULLMASTER) && !defined(DEST_RES_LOD)
    /* (DEST_RES_LOD pivot: the DDR master IS the 1280x720 LOD, not a 1920 master, so NO crop reprogram —
     * the base block's HSIZE/Stride/VSIZE = STRIDE(3840)/720 is already correct. Also the warp reads via its
     * own DataMover, not MM2S, so this leg is unused anyway.)
     * DIAGNOSTIC 2026-06-02: in full-master mode S2MM stores the full 1920×1080
     * master, but the output VTC raster is 1280×720. The MM2S (read) leg must
     * therefore read a geometry-correct CROP, else it streams a 1920-wide raster
     * into 1280-wide output timing and the lines wrap ("doubling" seen at
     * engine=0). Give MM2S: HSIZE = 1280*3 valid bytes/line, Stride = 5760 (the
     * master line pitch in DDR, unchanged), VSIZE = 720 lines → a clean top-left
     * 1280×720 crop of the master with NO scaling. S2MM (write) stays full
     * 1920×1080. NOTE: this makes the read geometry differ from the write
     * geometry — watch the dynamic-genlock handshake (see
     * schindler_genlock_geometry_must_match); revert if HDMI loses lock. */
    if (direction == XAXIVDMA_READ) {
        cfg.VertSizeInput = OUT_RASTER_H;            /* 720 lines              */
        cfg.HoriSizeInput = OUT_RASTER_W * BYTES_PP; /* 1280*3 = 3840 valid B  */
        /* cfg.Stride stays STRIDE (5760) = DDR master line pitch */
    }
#endif
    /* Phase D iter-4d-3: MM2S as genlock slave with FrameDelay=1 — slave
     * trails master by 1 frame in the 3-FB ring, hardware-enforced (PG020:
     * "Slave follows the Master by the frames set in Frame Delay register
     * either by skipping or repeating frames"). S2MM stays at 0 since it's
     * the master and free-runs at source rate.
     *
     * Replaces iter-4d-2's firmware PARK loop. That approach (PARK mode +
     * per-vsync PARK_PTR_REG writes from firmware) was non-atomic at MM2S
     * SOF; the writes landed mid-burst and produced 2-3 horizontal seams
     * per frame. Xilinx never intended PARK + firmware for live video — the
     * documented FRC path is Dynamic Genlock master/slave (iter-4d-3 step 2
     * upgrades from plain to Dynamic), and even plain genlock + FrameDelay=1
     * should kill the seams that PARK was hand-rolling badly. */
    /* MM2S follows S2MM by 1 frame in Dynamic Genlock (the standard pairing).
     * Note: per iter4h FrameDelay observation, this register reads-as-zero
     * in our IP config — the value is set per spec but Xilinx's IP locks the
     * bits. We keep the assignment for documentation / matching reference
     * designs. See memory: xilinx-vdma-dmasr-bits + schindler-bottom-bars-artifact. */
    cfg.FrameDelay        = (direction == XAXIVDMA_READ) ? 1 : 0;
    cfg.EnableCircularBuf = 1;
    /* EnableSync=1 on MM2S asserts DMACR bit 3, which enables slave-mode
     * frame-pointer following (required for FrameDelay/genlock to apply).
     * It is NOT the per-frame fsync gate we were treating it as in iter-4d-2. */
    cfg.EnableSync        = (direction == XAXIVDMA_READ) ? 1 : 0;
    cfg.PointNum          = 0;
    cfg.EnableFrameCounter = 0;
    cfg.FixedFrameStoreAddr = 0;

    status = XAxiVdma_DmaConfig(&vdma, direction, &cfg);
    if (status != XST_SUCCESS) {
        xil_printf("VDMA DmaConfig %s failed: %d\r\n",
                   (direction == XAXIVDMA_WRITE) ? "S2MM" : "MM2S", status);
        return status;
    }

    status = XAxiVdma_DmaSetBufferAddr(&vdma, direction, frame_addrs);
    if (status != XST_SUCCESS) {
        xil_printf("VDMA SetBufferAddr %s failed: %d\r\n",
                   (direction == XAXIVDMA_WRITE) ? "S2MM" : "MM2S", status);
        return status;
    }

    status = XAxiVdma_DmaStart(&vdma, direction);
    if (status != XST_SUCCESS) {
        xil_printf("VDMA DmaStart %s failed: %d\r\n",
                   (direction == XAXIVDMA_WRITE) ? "S2MM" : "MM2S", status);
        return status;
    }

    return XST_SUCCESS;
}

