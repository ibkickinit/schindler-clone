static unsigned g_gamma      = 0;     /* gamma: 0=off/linear, else gamma*10 */
static unsigned g_range      = 0;     /* input range: 0=full (0-255), 1=limited (16-235 expand) */
static unsigned g_freeze     = 0;     /* freeze: halt S2MM writer -> frame_ptr holds -> static read */
static u32      g_s2mm_vsize = 0;     /* saved S2MM VSIZE (@0x80) to re-arm the transfer on un-freeze */

static void colortemp_preset(unsigned k)
{
    /* CONTINUOUS white-balance tint from Kelvin (3200..10000), piecewise-linear between the
     * calibrated anchors below — exact at the old presets, smooth in between (for a 100K slider).
     * Relative to D65 (6500K) = video/display neutral. Warmer (<6500) cuts blue; cooler (>6500)
     * cuts red. Approximate operator "look", not chromaticity-calibrated. */
    static const unsigned KA[6] = {3200,4800,5600,6500,8000,10000};
    static const int      RA[6] = {255, 255, 255, 255, 230, 205};
    static const int      GA[6] = {220, 235, 246, 255, 242, 228};
    static const int      BA[6] = {160, 195, 225, 255, 255, 255};
    unsigned i;
    if (k == 0u) k = 6500u;                                 /* 0 = neutral = D65 */
    g_colortemp = k;
    if (k <= KA[0]) { g_white_r=RA[0]; g_white_g=GA[0]; g_white_b=BA[0]; return; }
    if (k >= KA[5]) { g_white_r=RA[5]; g_white_g=GA[5]; g_white_b=BA[5]; return; }
    for (i = 0; i < 5u; i++) {
        if (k <= KA[i+1]) {
            int span = (int)(KA[i+1]-KA[i]), d = (int)(k-KA[i]);
            g_white_r = (unsigned)(RA[i] + (RA[i+1]-RA[i])*d/span);   /* lerp (signed deltas) */
            g_white_g = (unsigned)(GA[i] + (GA[i+1]-GA[i])*d/span);
            g_white_b = (unsigned)(BA[i] + (BA[i+1]-BA[i])*d/span);
            return;
        }
    }
}

static void operator_apply(void)
{
    if (g_bypass) {                                  /* proc-amp bypass = full identity */
        color_set(0x8000, 0,0,0, 255,255,255);
        color_matrix_identity();
        return;
    }
    if (g_mono) color_matrix_saturation(0);          /* grayscale */
    else        color_matrix_saturation(color_sat_from_percent(g_matrix_sat_pct));
    /* color_correct white-point scaled by the fade level (255 = full, 0 = black) */
    u8 wr = (u8)(((unsigned)g_white_r * g_fade_level) / 255u);
    u8 wg = (u8)(((unsigned)g_white_g * g_fade_level) / 255u);
    u8 wb = (u8)(((unsigned)g_white_b * g_fade_level) / 255u);
    color_set(g_sat_q15, g_black_r, g_black_g, g_black_b, wr, wg, wb);
}

static int parse_uint(const char **pp, unsigned *out)
{
    const char *p = *pp;
    while (*p == ' ' || *p == '\t') p++;
    if (*p < '0' || *p > '9') return 0;
    unsigned v = 0;
    while (*p >= '0' && *p <= '9') { v = v * 10 + (*p - '0'); p++; }
    *out = v;
    *pp = p;
    return 1;
}

/* signed variant: accepts an optional leading '-' (used for the shift offsets,
 * which may be negative = move the image off the left/top edge). */
static int parse_int(const char **pp, int *out)
{
    const char *p = *pp;
    while (*p == ' ' || *p == '\t') p++;
    int neg = 0;
    if (*p == '-') { neg = 1; p++; }
    else if (*p == '+') { p++; }
    if (*p < '0' || *p > '9') return 0;
    int v = 0;
    while (*p >= '0' && *p <= '9') { v = v * 10 + (*p - '0'); p++; }
    *out = neg ? -v : v;
    *pp = p;
    return 1;
}

